def build() -> list[dict]:
    out = []
    for cid, disp, syns, unit, conv in ANALYTES + NEW_ANALYTES:
        extra = EXTRA_SYNONYMS.get(cid, []) + BIOLAB_SYNONYMS.get(cid, []) + PANEL_SYNONYMS.get(cid, [])
        merged = list(dict.fromkeys([*syns, *extra]))  # de-dupe, keep order
        out.append({
            "canonical_id": cid,
            "display_name_cs": disp,
            "synonyms": merged,
            "canonical_unit": unit,
            "unit_conversions": {**conv, **EXTRA_CONVERSIONS.get(cid, {})},
        })
    return out


def collisions(data: list[dict]) -> list[str]:
    """Every index key two analytes would both claim: the canonical id with
    underscores as spaces (matching.py and registry.ts agree on that), the
    display name, every synonym, and the trailing "[ABBR]" that is a second
    key on both sides. Empty when the seed is safe to ship.

    Guard seen failing (2026-09-19, first run over the widened catalog):
    "TET_IgG" stripped to "igg", "Ca++" folded to "ca", "PT %" to "pt",
    "β-globuliny" and "γ-globuliny" both to "globuliny" — each would have
    trended a different test under a known name.
    """
    from src.matching import abbreviation_key, norm_key

    claims: dict[str, set[str]] = {}
    seen_ids: set[str] = set()
    out: list[str] = []
    for a in data:
        cid = a["canonical_id"]
        if cid in seen_ids:
            out.append(f"duplicate id {cid!r}")
        seen_ids.add(cid)
        names = [cid.replace("_", " "), a["display_name_cs"], *a["synonyms"]]
        keys = {norm_key(n) for n in names} | {k for k in (abbreviation_key(n) for n in names) if k}
        keys.discard("")
        for k in keys:
            claims.setdefault(k, set()).add(cid)
    for k, ids in sorted(claims.items()):
        if len(ids) > 1:
            out.append(f"key {k!r} claimed by {', '.join(sorted(ids))}")
    return out


